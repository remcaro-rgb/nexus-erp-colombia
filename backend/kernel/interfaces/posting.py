"""PostingService (owner P05, ADR-005, shared/07).

Contract:
* Called **inside** the caller's unit of work (``kernel.uow.require_uow()``);
  never opens its own transaction; failure → the whole document rolls back.
* Pre: request lines reference accounts by role/determination keys; amounts
  are Decimal; currency ISO 4217; the posting date's period is OPEN.
* Post: exactly one balanced entry (Σdebit = Σcredit per currency and in COP);
  rounding / FX_ROUNDING lines generated by the engine, never by callers;
  rows immutable; the entry references ``request.source``.
* Idempotency: ``(company_id, source.type, source.id, purpose)`` posts once; a
  second call returns the existing result.
* Errors: ``period_closed``, ``unbalanced_entry``, ``account_not_found``,
  ``dimension_required``, ``dimension_forbidden``, ``dimension_node_not_postable``.
"""

from __future__ import annotations

import datetime as dt
import uuid
from dataclasses import dataclass, field
from decimal import Decimal
from typing import Literal, Protocol, runtime_checkable

from kernel.interfaces.common import DimensionValues, DocumentRef, PartyRef
from kernel.uow import UnitOfWork


@dataclass(frozen=True, slots=True)
class PostingLine:
    account_role: str
    side: Literal["DEBIT", "CREDIT"]
    amount: Decimal
    currency: str = "COP"
    fx_rate: Decimal = Decimal(1)
    party: PartyRef | None = None
    tax_code: str | None = None
    item_id: uuid.UUID | None = None
    warehouse_id: uuid.UUID | None = None
    dimensions: DimensionValues = field(default_factory=DimensionValues)
    memo: str = ""


@dataclass(frozen=True, slots=True)
class PostingRequest:
    company_id: uuid.UUID
    posting_date: dt.date
    source: DocumentRef
    purpose: str
    lines: tuple[PostingLine, ...]
    journal_code: str = "GENERAL"
    branch_id: uuid.UUID | None = None


@dataclass(frozen=True, slots=True)
class PostingResult:
    entry_id: uuid.UUID
    entry_number: str
    total_debit_cop: Decimal
    total_credit_cop: Decimal
    replayed: bool = False


@runtime_checkable
class PostingService(Protocol):
    def post(self, uow: UnitOfWork, request: PostingRequest) -> PostingResult:
        """Create the balanced journal entry for ``request`` (see module docstring)."""
        ...

    def simulate(self, uow: UnitOfWork, request: PostingRequest) -> PostingResult:
        """Same validations as :meth:`post`, writes nothing; returns the would-be totals."""
        ...

    def reverse(self, uow: UnitOfWork, entry_id: uuid.UUID, reversal_date: dt.date, reason: str) -> PostingResult:
        """Post a reversal entry linked to ``entry_id`` (never deletes, C1-5)."""
        ...
