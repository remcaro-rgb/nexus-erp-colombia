# --- field encryption key (FIX-D-W01-1) -------------------------------------------
# ERP_FIELD_ENCRYPTION_KEY or ERP_FIELD_ENCRYPTION_KEY_FILE: url-safe base64 of 32
# bytes (generated by deploy/dev/gen-secrets.sh, never committed). Optional here;
# the dev profile requires it, the test profile uses an ephemeral per-process key.


def read_field_key(environ: Mapping[str, str], *, required: bool) -> str | None:
    value = read_secret("ERP_FIELD_ENCRYPTION_KEY", environ, required=required)
    if value is None:
        return None
    try:
        raw = base64.urlsafe_b64decode(value.encode("ascii"))
    except (binascii.Error, ValueError, UnicodeEncodeError):
        raw = b""
    if len(raw) != 32:
        raise ConfigError(
            "ERP_FIELD_ENCRYPTION_KEY must be url-safe base64 of 32 bytes (run deploy/dev/gen-secrets.sh)"
        )
    return value


ERP_FIELD_ENCRYPTION_KEY = read_field_key(os.environ, required=False)

