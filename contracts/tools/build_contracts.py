class Builder:
    def __init__(self):
        self.root = load_yaml(os.path.join(SRC, "root.yaml"))
        self.errors = load_yaml(os.path.join(CONTRACTS, "errors.yaml"))
        self.error_codes = [e["code"] for e in self.errors["codes"]]
        self.roles = load_yaml(os.path.join(SRC, "roles.yaml"))
        self.modules = []
        mdir = os.path.join(SRC, "modules")
        for fn in sorted(os.listdir(mdir)):
            if fn.endswith(".yaml"):
                m = load_yaml(os.path.join(mdir, fn))
                m["_file"] = fn
                self.modules.append(m)
        self.outputs = OrderedDict()  # relpath -> text
        self.op_ids = set()
        self.perms = OrderedDict()   # code -> {description, module, owner, operations}

    # ------------------------------------------------------------------ OpenAPI building
    def schema_for_resource(self, mod, res, comps):
        name = res.get("schema") or camel(singular(res["path"].split("/")[-1].replace("{", "").replace("}", "")))
        if name in comps:
            return name
        kind = res.get("kind", "master")
        fields = OrderedDict()
        fields["id"] = "uuid public ro"
        fields["tenant_id"] = "uuid internal ro"
        if not mod.get("tenant_level") and not res.get("tenant_level"):
            fields["company_id"] = "uuid internal ro"
        for k, v in KIND_FIELDS.get(kind, {}).items():
            fields[k] = v
        for k, v in (res.get("fields") or {}).items():
            if v is None:
                fields.pop(k, None)
            else:
                fields[k] = v
        if kind == "document" or res.get("lines"):
            line_name = name + "Line"
            lf = OrderedDict(LINE_DEFAULT)
            for k, v in (res.get("lines") or {}).items():
                lf[k] = v
            comps[line_name] = self.object_schema(lf, f"Line of {name}")
            fields["lines"] = f"array(@{line_name}) internal"
        fields["version"] = "int internal ro"
        fields["audit"] = "audit internal ro"
        comps[name] = self.object_schema(fields, res.get("description") or f"{camel(mod['module'])} {res['path']}")
        if res.get("ops_set") & {"create", "update", "put"}:
            writable = OrderedDict((k, v) for k, v in fields.items() if " ro" not in f" {v} " and k not in ("status",))
            inp = self.object_schema(writable, f"Create/replace body of {name}", required_from=True)
            comps[name + "Input"] = inp
            patch = self.object_schema(writable, f"Partial update body of {name} (state never changes through PATCH; use action endpoints)")
            patch.pop("required", None)
            patch["minProperties"] = 1
            comps[name + "Patch"] = patch
        return name

    def object_schema(self, fields, description, required_from=False):
        props, req = OrderedDict(), []
        for k, v in fields.items():
            s, ro, r = field_schema(k, v)
            props[k] = s
            if r and required_from:
                req.append(k)
        out = {"type": "object", "description": description, "additionalProperties": False, "properties": dict(props)}
        if required_from and req:
            out["required"] = req
        elif not required_from:
            req2 = [k for k, v in fields.items() if parse_field(v)[3] or k in ("id",)]
            if req2:
                out["required"] = req2
        return out

    def perm_code(self, mod, res, action):
        return f"{mod.get('perm_module', snake(mod['module']))}.{res.get('perm') or singular(res['path'].split('/')[-1].strip('{}'))}.{action}"

    def add_perm(self, code, mod, op_id, summary):
        if not PERM_RE.match(code):
            raise SystemExit(f"{mod['_file']}: bad permission code {code}")
        p = self.perms.setdefault(code, {"code": code, "module": code.split(".")[0], "owner": mod["owner"], "description": summary, "operations": []})
        p["operations"].append(op_id)

    def op_id(self, mod, path, name):
        rel = path.split("/v1/", 1)[1]
        rel = re.sub(r"\{[^}]+\}", "by", rel)
        tail = rel.rsplit(":", 1)[1] if ":" in rel else None
        oid = snake(rel.replace(":", "_") + ("" if tail is not None and snake(tail) == snake(name) else "_" + name))
        oid = re.sub(r"_+", "_", oid)
        base, i = oid, 2
        while oid in self.op_ids:
            oid, i = f"{base}_{i}", i + 1
        self.op_ids.add(oid)
        return oid

    def responses(self, codes, ok):
        r = OrderedDict(ok)
        r["400"] = {"$ref": "ROOT_RESP:BadRequest"}
        r["401"] = {"$ref": "ROOT_RESP:Unauthorized"}
        r["403"] = {"$ref": "ROOT_RESP:Forbidden"}
        if "not_found" in codes:
            r["404"] = {"$ref": "ROOT_RESP:NotFound"}
        if set(codes) & {"idempotency_conflict", "invalid_state_transition", "dimension_in_use", "reservation_conflict"} or any(
                self.http_of(c) == 409 for c in codes):
            r["409"] = {"$ref": "ROOT_RESP:Conflict"}
        if "version_conflict" in codes:
            r["412"] = {"$ref": "ROOT_RESP:PreconditionFailed"}
        if any(self.http_of(c) == 422 for c in codes):
            r["422"] = {"$ref": "ROOT_RESP:Unprocessable"}
        if "precondition_required" in codes:
            r["428"] = {"$ref": "ROOT_RESP:PreconditionRequired"}
        r["429"] = {"$ref": "ROOT_RESP:TooManyRequests"}
        return dict(r)

    def http_of(self, code):
        for e in self.errors["codes"]:
            if e["code"] == code:
                return e["http"]
        return None

    def make_op(self, mod, res, path, method, name, perm_action, summary, *, body=None, ok=None, params=None, extra_errors=(),
                idem=False, ifmatch=None, list_params=False, features=None, reason=False):
        oid = self.op_id(mod, path, name)
        code = self.perm_code(mod, res, perm_action)
        owner = res.get("owner") or mod["owner"]
        self.add_perm(code, {**mod, "owner": owner}, oid, summary)
        errs = list(COMMON_ERRORS)
        if "{" in path:
            errs.append("not_found")
        if idem:
            errs += MUTATING_ERRORS
        if ifmatch == "required":
            errs += UPDATE_ERRORS
        if perm_action in ("post", "approve", "void"):
            errs += POST_ERRORS
        if reason:
            errs.append("reason_required")
        if list_params:
            errs.append("filter_invalid")
        errs += list(res.get("errors") or []) + list(extra_errors)
        errs = list(OrderedDict.fromkeys(errs))
        for e in errs:
            if e not in self.error_codes:
                raise SystemExit(f"{mod['_file']}: {path} uses unregistered error code {e}")
        ps = [{"$ref": f"ROOT_PARAM:{p}"} for p in ([] if mod.get("portal") else ["CompanyHeader"])]
        for pname in re.findall(r"\{([^}]+)\}", path):
            ps.insert(0, {"name": pname, "in": "path", "required": True,
                          "schema": {"type": "string", "format": "uuid"} if pname.endswith("id") else {"type": "string"}})
        if idem:
            ps.append({"$ref": "ROOT_PARAM:IdempotencyKey"})
        if ifmatch == "required":
            ps.append({"$ref": "ROOT_PARAM:IfMatch"})
        elif ifmatch == "optional":
            ps.append({"$ref": "ROOT_PARAM:IfMatchOptional"})
        if list_params:
            ps += [{"$ref": f"ROOT_PARAM:{p}"} for p in ("Cursor", "Limit", "Sort", "Fields", "Filter", "Query")]
        for p in params or []:
            ps.append({"name": p, "in": "query", "required": False, "schema": {"type": "string", "maxLength": 200}})
        op = OrderedDict()
        op["operationId"] = oid
        op["summary"] = summary
        op["tags"] = [mod["title"]]
        op["x-permission"] = code
        op["x-owner"] = owner
        feats = sorted(set((res.get("features") or []) + list(features or [])))
        if feats:
            op["x-features"] = feats
        op["x-error-codes"] = errs
        if idem:
            op["x-idempotent"] = True
        if mod.get("portal"):
            op["security"] = [{"oauth2": ["portal"]}]
            op["x-portal"] = res.get("portal_kind") or mod["portal"]
        op["parameters"] = ps
        if body is not None:
            op["requestBody"] = body
        op["responses"] = self.responses(errs, ok)
        return method, dict(op)

    @staticmethod
    def json_ok(status, schema_ref, desc="OK", headers=None):
        r = {"description": desc, "content": {"application/json": {"schema": schema_ref}}}
        if headers:
            r["headers"] = headers
        return {str(status): r}

    @staticmethod
    def body(schema_ref, required=True):
        return {"required": required, "content": {"application/json": {"schema": schema_ref}}}

    def accepted(self):
        return {"202": {"description": "Accepted; poll the operation", "headers": {"Location": {"$ref": "ROOT_HDR:Location"}},
                        "content": {"application/json": {"schema": {"$ref": "ROOT:Operation"}}}}}

    def file_ok(self, ext):
        return {"200": {"description": f"{ext.upper()} file", "content": {FILE_TYPES[ext]: {"schema": {"type": "string", "contentMediaType": FILE_TYPES[ext]}}}}}

    def build_module(self, mod):
        base = mod.get("base") or f"/api/v1/{mod['module']}"
        comps = OrderedDict()
        paths = OrderedDict()

        def put(path, method_op):
            method, op = method_op
            paths.setdefault(path, OrderedDict())
            if method in paths[path]:
                raise SystemExit(f"{mod['_file']}: duplicate {method.upper()} {path}")
            paths[path][method] = op

        for res in mod.get("resources", []):
            kind = res.get("kind", "master")
            default_ops = {"master": "list create get update delete", "document": "list create get update delete",
                           "config": "list create get update delete", "readonly": "list get", "record": "list create get",
                           "report": "", "singleton": "getone put", "process": "", "collection": "list create"}[kind]
            ops = res.get("ops", default_ops)
            ops = ops.split() if isinstance(ops, str) else list(ops)
            if kind in ("report", "process"):
                ops = []
            res["ops_set"] = set(ops) | ({"update"} if "update" in ops else set())
            P = base + "/" + res["path"] if res["path"] else base
            label = res.get("label") or res["path"]
            sname = None
            if kind not in ("report", "process") and (ops or res.get("actions") or res.get("coll_actions")):
                sname = self.schema_for_resource(mod, res, comps)
            ref = {"$ref": f"#/components/schemas/{sname}"} if sname else None
            etag = {"ETag": {"$ref": "ROOT_HDR:ETag"}}
            if "list" in ops:
                page = sname + "Page"
                comps[page] = {"allOf": [{"$ref": "ROOT:Page"}, {"type": "object", "properties": {"items": {"type": "array", "items": ref, "x-classification": "internal"}}}]}
                put(P, self.make_op(mod, res, P, "get", "list", "read", f"Listar {label}", ok=self.json_ok(200, {"$ref": f"#/components/schemas/{page}"}),
                                    list_params=True, params=res.get("params")))
            if "create" in ops:
                put(P, self.make_op(mod, res, P, "post", "create", "create", f"Crear {label}", body=self.body({"$ref": f"#/components/schemas/{sname}Input"}),
                                    ok=self.json_ok(201, ref, "Created", {**etag, "Location": {"$ref": "ROOT_HDR:Location"}}), idem=True))
            if "getone" in ops:
                put(P, self.make_op(mod, res, P, "get", "get", "read", f"Consultar {label}", ok=self.json_ok(200, ref, headers=etag)))
            if "put" in ops:
                put(P, self.make_op(mod, res, P, "put", "replace", res.get("put_perm", "update"), f"Reemplazar {label}",
                                    body=self.body({"$ref": f"#/components/schemas/{sname}Input"}), ok=self.json_ok(200, ref, headers=etag), idem=True, ifmatch="required"))
            item = P + "/{id}"
            if "get" in ops:
                put(item, self.make_op(mod, res, item, "get", "get", "read", f"Consultar {label} por id", ok=self.json_ok(200, ref, headers=etag)))
            if "update" in ops:
                put(item, self.make_op(mod, res, item, "patch", "update", "update", f"Actualizar {label}" + (" (solo BORRADOR)" if kind == "document" else ""),
                                       body=self.body({"$ref": f"#/components/schemas/{sname}Patch"}), ok=self.json_ok(200, ref, headers=etag), idem=True, ifmatch="required",
                                       extra_errors=["document_immutable"] if kind == "document" else []))
            if "delete" in ops:
                put(item, self.make_op(mod, res, item, "delete", "delete", "delete", f"Eliminar {label}" + (" (solo BORRADOR)" if kind == "document" else " (solo sin uso)"),
                                       ok={"204": {"description": "Deleted"}}, idem=True, ifmatch="required",
                                       extra_errors=["document_immutable"] if kind == "document" else []))
            if kind == "report":
                put(P, self.report_op(mod, res, P, label))
            for a in res.get("actions") or []:
                self.action(mod, res, P + "/{id}", a, sname, put, instance=True)
            for a in res.get("coll_actions") or []:
                self.action(mod, res, P, a, sname, put, instance=False)
            for x in res.get("extra") or []:
                self.extra(mod, res, P, x, sname, put)
        for x in mod.get("extra_schemas") or []:
            for k, v in x.items():
                comps[k] = self.object_schema(v, k)
        return base, paths, comps

    def report_op(self, mod, res, P, label):
        ok = {"200": {"description": "Report (json) or export file", "content": {
            "application/json": {"schema": {"$ref": "ROOT:ReportResult"}},
            **{FILE_TYPES[x]: {"schema": {"type": "string", "contentMediaType": FILE_TYPES[x]}} for x in ("csv", "xlsx", "pdf")}}}}
        method, op = self.make_op(mod, res, P, "get", "report", res.get("perm_action", "read"), f"Informe {label}", ok=ok,
                                  params=res.get("params"), list_params=False, extra_errors=res.get("report_errors", []))
        op["parameters"].append({"$ref": "ROOT_PARAM:Format"})
        return method, op

    def action(self, mod, res, P, a, sname, put, instance):
        if isinstance(a, dict):
            verb, opts = next(iter(a.items()))
            opts = opts or {}
        else:
            verb, opts = a, {}
        path = f"{P}:{verb}"
        perm = opts.get("perm") or ACTION_PERM.get(verb, "update")
        method = opts.get("method", "get" if verb in GET_ACTIONS else "post")
        summary = opts.get("summary") or f"Acción {verb} sobre {res.get('label') or res['path']}"
        if verb == "bulk":
            ok = self.json_ok(200, {"$ref": "ROOT:BulkResult"})
            body = self.body({"$ref": "ROOT:BulkRequest"})
            extra = ["bulk_limit_exceeded"]
        elif verb in SIMULATION_ACTIONS or opts.get("returns") == "simulation":
            ok = self.json_ok(200, {"$ref": "ROOT:SimulationResult"})
            body = self.body({"$ref": "ROOT:ActionRequest"}, required=False)
            extra = []
        elif verb == "export" or opts.get("returns") == "file":
            ok = self.file_ok(opts.get("ext", "csv"))
            body = None
            extra = []
        elif verb in ASYNC_ACTIONS or opts.get("async"):
            ok = self.accepted()
            body = self.body({"$ref": "ROOT:ActionRequest"}, required=False)
            extra = []
        elif opts.get("returns") == "result" or not sname:
            ok = self.json_ok(200, {"$ref": "ROOT:ActionResult"})
            body = self.body({"$ref": "ROOT:ActionRequest"}, required=False)
            extra = []
        else:
            ok = self.json_ok(200, {"$ref": f"#/components/schemas/{sname}"}, headers={"ETag": {"$ref": "ROOT_HDR:ETag"}})
            body = self.body({"$ref": "ROOT:ActionRequest"}, required=False)
            extra = []
        if verb in ("import", "upload"):
            body = {"required": True, "content": {"multipart/form-data": {"schema": {"$ref": "ROOT:FileUploadRequest"}}}}
        mutating = method != "get" and perm not in ("read", "export") or method == "post"
        if method == "get":
            body = None
        put(path, self.make_op(mod, res, path, method, snake(verb), perm, summary, body=body, ok=ok, idem=mutating and method != "get",
                               ifmatch="optional" if (instance and method == "post" and perm not in ("read", "export")) else None,
                               extra_errors=extra + list(opts.get("errors", [])), features=opts.get("features"),
                               reason=verb in REASON_ACTIONS, params=opts.get("params")))

    def extra(self, mod, res, P, x, sname, put):
        sub = x["path"]
        path = P + (sub if sub.startswith(":") else "/" + sub.lstrip("/")) if sub else P
        method = x.get("method", "get").lower()
        name = x.get("op") or snake(sub.split("/")[-1].split(":")[-1].replace(".", "_")) or method
        perm = x.get("perm") or ACTION_PERM.get(name.replace("_", "-"), "read" if method == "get" else "update")
        returns = x.get("returns", "json")
        if returns.startswith("file:"):
            ok = self.file_ok(returns.split(":", 1)[1])
        elif returns == "page":
            ok = self.json_ok(200, {"$ref": "ROOT:Page"})
        elif returns == "report":
            ok = self.json_ok(200, {"$ref": "ROOT:ReportResult"})
        elif returns == "tree":
            ok = self.json_ok(200, {"type": "array", "items": {"$ref": "ROOT:TreeNode"}})
        elif returns == "usage":
            ok = self.json_ok(200, {"$ref": "ROOT:UsageResult"})
        elif returns == "simulation":
            ok = self.json_ok(200, {"$ref": "ROOT:SimulationResult"})
        elif returns == "operation":
            ok = self.accepted()
        elif returns == "schema" and sname:
            ok = self.json_ok(200, {"$ref": f"#/components/schemas/{sname}"})
        elif returns == "sse":
            ok = {"200": {"description": "Server-sent events stream", "content": {"text/event-stream": {"schema": {"type": "string"}}}}}
        else:
            ok = self.json_ok(200, {"$ref": "ROOT:ActionResult"})
        body = None
        if method in ("post", "put", "patch"):
            body = self.body({"$ref": "ROOT:ActionRequest"}, required=False)
            if x.get("body") == "upload":
                body = {"required": True, "content": {"multipart/form-data": {"schema": {"$ref": "ROOT:FileUploadRequest"}}}}
        mutating = method in ("post", "put", "patch", "delete") and perm not in ("read",)
        if method in ("post", "put", "patch", "delete") and perm == "read":
            mutating = True  # every POST carries Idempotency-Key (stateless calculations replay safely)
        put(path, self.make_op(mod, res, path, method, name, perm, x.get("summary") or f"{name} de {res.get('label') or res['path']}",
                               body=body, ok=ok, idem=mutating, ifmatch="required" if method in ("put", "patch") else None,
                               params=x.get("params"), extra_errors=x.get("errors", []), features=x.get("features"),
                               list_params=returns == "page"))

    # ------------------------------------------------------------------ refs
    @staticmethod
    def rewrite_refs(obj, mode):
        """mode 'bundle' -> local refs; 'fragment' -> ../root.yaml refs; 'root' -> local refs."""
        if isinstance(obj, dict):
            out = {}
            for k, v in obj.items():
                if k == "$ref" and isinstance(v, str) and v.split(":", 1)[0] in ("ROOT", "ROOT_RESP", "ROOT_PARAM", "ROOT_HDR"):
                    kind, name = v.split(":", 1)
                    sect = {"ROOT": "schemas", "ROOT_RESP": "responses", "ROOT_PARAM": "parameters", "ROOT_HDR": "headers"}[kind]
                    out[k] = (f"../root.yaml#/components/{sect}/{name}" if mode == "fragment" else f"#/components/{sect}/{name}")
                else:
                    out[k] = Builder.rewrite_refs(v, mode)
            return out
        if isinstance(obj, list):
            return [Builder.rewrite_refs(x, mode) for x in obj]
        return obj

    # ------------------------------------------------------------------ events
    def event_payload_schema(self, ev):
        fields = OrderedDict(ev.get("payload") or {})
        props, req = {}, []
        for k, v in fields.items():
            s, ro, r = field_schema(k, v)
            props[k] = s
            if r:
                req.append(k)
        return {"type": "object", "additionalProperties": False, "properties": props, "required": req}

    def resolve_root(self, schema):
        """Inline ROOT: refs (for self-contained event JSON Schemas)."""
        rs = self.root["components"]["schemas"]
        def walk(o):
            if isinstance(o, dict):
                if "$ref" in o and isinstance(o["$ref"], str) and o["$ref"].startswith("ROOT:"):
                    name = o["$ref"].split(":", 1)[1]
                    extra = {k: v for k, v in o.items() if k != "$ref"}
                    base = walk(copy.deepcopy(rs[name]))
                    base.update(extra)
                    return base
                if "$ref" in o and isinstance(o["$ref"], str) and o["$ref"].startswith("#/components/schemas/"):
                    name = o["$ref"].rsplit("/", 1)[1]
                    extra = {k: v for k, v in o.items() if k != "$ref"}
                    base = walk(copy.deepcopy(rs[name]))
                    base.update(extra)
                    return base
                return {k: walk(v) for k, v in o.items()}
            if isinstance(o, list):
                return [walk(x) for x in o]
            return o
        return walk(schema)

