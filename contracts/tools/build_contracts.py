# ------------------------------------------------------------------------------------------------ helpers
def load_yaml(p):
    with open(p, encoding="utf-8") as fh:
        return yaml.safe_load(fh)


def camel(s):
    return "".join(w[:1].upper() + w[1:] for w in re.split(r"[^A-Za-z0-9]+", s) if w)


def snake(s):
    return re.sub(r"[^a-z0-9]+", "_", s.lower()).strip("_")


def singular(s):
    s = snake(s)
    for a, b in (("ies", "y"), ("sses", "ss"), ("ches", "ch"), ("shes", "sh"), ("xes", "x"), ("s", "")):
        if s.endswith(a) and len(s) > len(a) + 1 and not s.endswith("ss"):
            return s[: -len(a)] + b
    return s


def parse_field(spec):
    """'money internal ro req' / 'enum(A|B) public' / 'array(ref)' / 'array(@Line)' / '@Schema'."""
    toks = str(spec).split()
    t, flags = toks[0], toks[1:]
    cls = next((f for f in flags if f in CLASSIFICATIONS), None)
    return t, cls, "ro" in flags, "req" in flags, "wo" in flags, "null" in flags


def type_schema(t, comp_prefix):
    m = re.match(r"^enum\((.+)\)$", t)
    if m:
        return {"type": "string", "enum": m.group(1).split("|")}
    m = re.match(r"^array\((.+)\)$", t)
    if m:
        return {"type": "array", "items": type_schema(m.group(1), comp_prefix)}
    if t.startswith("@"):
        return {"$ref": f"#/components/schemas/{t[1:]}"}
    if t not in TYPE_BASE:
        raise SystemExit(f"unknown field type {t!r}")
    return copy.deepcopy(TYPE_BASE[t])


def field_schema(name, spec, comp_prefix=""):
    t, cls, ro, req, wo, nullable = parse_field(spec)
    s = type_schema(t, comp_prefix)
    base_t = re.sub(r"\(.*", "", t)
    s["x-classification"] = cls or DEFAULT_CLASS.get(base_t, "internal")
    if ro:
        s["readOnly"] = True
    if wo:
        s["writeOnly"] = True
    if nullable and "type" in s and isinstance(s["type"], str):
        s["type"] = [s["type"], "null"]
    return s, ro, req


